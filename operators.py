#Arithmetic Operators

a, b = 20, 6
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)

# negative floor division
print(-7 // 2)
print(-7 % 2)

#Relational / Comparison Operators

m, n = 10, 20
print(m == n)
print(m != n)
print(m > n)
print(m < n)
print(m >= n)
print(m <= n)

#chained comparisons
age = 22
print(18 <= age < 30)

